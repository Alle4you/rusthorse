#!/bin/sh
# Build the Debian package: target/debian/rusthorse_<version>-1_<arch>.deb
#
# Needs what building from source needs (Rust, the GTK 4 and libadwaita
# development packages) and cargo-deb (`cargo install --locked cargo-deb`).
# The package is described in Cargo.toml, [package.metadata.deb]; the files
# it installs besides the programs are in packaging/deb/ and data/.
# Extra arguments go to cargo-deb (for example `--output DIR`).
#
# Build on the oldest release the package should install on: the package
# depends on the versions of GTK, libadwaita and glibc it was built against
# (Ubuntu 24.04 gives a package for Ubuntu 24.04 and Linux Mint 22 or later,
# and for Debian 13).
set -eu

cd "$(dirname "$0")/.."

# One build for the three programs, so that `rusthorse` keeps its default
# features (the dialog and the manager use the library without them).
cargo build --release --locked --workspace

# Shell completions, generated by the program that will be installed.
completions=target/release/packaging/completions
rm -rf "$completions"
mkdir -p "$completions"
target/release/rusthorse completions bash >"$completions/rusthorse"
target/release/rusthorse completions zsh >"$completions/_rusthorse"
target/release/rusthorse completions fish >"$completions/rusthorse.fish"

cargo deb --no-build --locked -p rusthorse "$@"
